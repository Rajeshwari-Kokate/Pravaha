"""
Pydantic schemas for Google Gemma 4 Technical Investigation Reports.
Enforces strict sectioning, evidence citation formatting, and validation.
"""

from typing import List, Dict, Optional, Literal
from pydantic import BaseModel, Field, field_validator
import re

EVIDENCE_REGEX = re.compile(r"\[EVID-[A-Z0-9_\-]+\]")


class HotspotFinding(BaseModel):
    conduit_id: str = Field(description="Identifier of the overloaded drainage conduit")
    channel_type: str = Field(description="Channel classification (trunk, primary, secondary, roadside)")
    flow_ratio: float = Field(description="Ratio of peak inflow to effective capacity")
    severity: str = Field(description="Severity classification: low, moderate, high, critical")
    evidence_id: str = Field(description="Explicit citation matching an evidence registry item, e.g. [EVID-SIM-03]")

    @field_validator("evidence_id")
    @classmethod
    def validate_citation(cls, v: str) -> str:
        if not EVIDENCE_REGEX.search(v):
            raise ValueError(f"Invalid evidence citation '{v}'. Must match format [EVID-...]")
        return v


class CandidateBottleneck(BaseModel):
    conduit_id: str = Field(description="Identifier of bottleneck conduit")
    rank: int = Field(ge=1, description="Bottleneck severity ranking (1 = worst)")
    composite_score: float = Field(description="Multi-factor composite risk score [0, 1]")
    primary_driver: str = Field(description="Leading contributing factor (e.g. cross-section constriction, heavy upstream confluence)")
    evidence_id: str = Field(description="Explicit evidence citation, e.g. [EVID-SIM-05]")

    @field_validator("evidence_id")
    @classmethod
    def validate_citation(cls, v: str) -> str:
        if not EVIDENCE_REGEX.search(v):
            raise ValueError(f"Invalid evidence citation '{v}'. Must match format [EVID-...]")
        return v


class InvestigationReport(BaseModel):
    report_id: str = Field(description="Unique report identifier, e.g. REP-2026-001")
    run_id: str = Field(description="Simulation run UUID")
    scenario_name: str = Field(description="Name of modeled storm scenario")
    generated_at: str = Field(description="ISO 8601 generation timestamp")
    generated_by_model: str = Field(description="Model identifier, e.g. google/gemma-4-E4B-it or deterministic-fallback")
    is_fallback: bool = Field(default=False, description="True if generated by local deterministic heuristics due to unreachable LLM")
    
    executive_summary: str = Field(
        min_length=20,
        description="Comprehensive technical summary linking simulation results to evidence IDs"
    )
    hotspot_findings: List[HotspotFinding] = Field(
        default_factory=list,
        description="Critical conduit exceedances with explicit evidence links"
    )
    candidate_bottlenecks: List[CandidateBottleneck] = Field(
        default_factory=list,
        description="Top ranked drainage bottlenecks requiring municipal intervention"
    )
    intervention_comparison: str = Field(
        min_length=20,
        description="Comparative assessment of desilting, widening, or relief routing options"
    )
    data_limitations: List[str] = Field(
        min_length=1,
        description="Explicit engineering caveats and data provenance constraints"
    )
    inspection_recommendations: List[str] = Field(
        min_length=1,
        description="Field inspection priorities and CCTV culvert survey instructions"
    )
    evidence_citations: List[str] = Field(
        default_factory=list,
        description="All explicit evidence IDs referenced across this document"
    )


class ReportGenerationRequest(BaseModel):
    run_id: str = Field(description="UUID of simulation run stored in SQLite or passed in memory")
    custom_instructions: Optional[str] = Field(default=None, description="Optional municipal engineer notes or area focus")
